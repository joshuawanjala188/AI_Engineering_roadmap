#They store unique values, no repeating values
#duplicates are automatically removed

a = {1, 2, 3, 4}
b = {3, 4, 5, 6}

#union- everything in either set
print(a|b)

#intersection - values shared by both

print(a & b)

#Difference - valuea in a but not b

print(a - b)

